colorpal <- function(n){
  if(n > 20){
    stop("Not enough colors")
  }
  c("#88CCEE", "#DDCC77", "#CC6677", "#117733", "#332288", 
    "#AA4499", "#44AA99", "#999933", "#882255", "#661100", 
    "#6699CC", "#888888", "#E69F00", "#56B4E9", "#009E73", 
    "#F0E442", "#0072B2", "#D55E00", "#CC79A7", "#999999")[seq_len(n)]
}